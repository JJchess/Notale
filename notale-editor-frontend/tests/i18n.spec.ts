import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {unzipSync,strFromU8} from 'fflate';
import {reveal} from './harness/format-panel';
test.use({baseURL:process.env.I18N_URL??'http://127.0.0.1:4420'});

test('language switches preserve editing state, authored text and export language',async({page,context})=>{
 const id=randomUUID();
 const created=await page.request.post('/api/documents',{data:{schemaVersion:1,id,title:'保存',width:1600,height:900,slides:[{id:'first',name:'开始',sourcePath:'first.html',notes:'讲稿：保存',html:'<html><body><main id="stage" data-notale-id="stage" style="width:1600px;height:900px"><a data-notale-id="link" data-notale-name="保存" href="https://example.com" style="position:absolute;left:100px;top:100px;width:300px;height:100px;font-size:36px">中文原文</a></main></body></html>'}]}});
 expect(created.ok()).toBe(true);
 await page.goto('/?document='+id,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>(window as any).NotaleWorkbench?.getSnapshot()?.document.id);
 await page.evaluate(()=>(window as any).NotaleWorkbench.whenReady());
 const original=await page.request.get('/api/documents/'+id).then(r=>r.json());
 await page.evaluate(()=>{(window as any).__localeFrame=document.querySelector('#canvas');(window as any).NotaleWorkbench.select('link');});
 await reveal(page,'#link-url');await page.locator('#link-url').fill('https://example.org/未提交');
 await page.locator('.language-menu>summary').click();await page.getByRole('button',{name:'English',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('lang','en-US');
 await expect(page.locator('#undo')).toHaveAttribute('aria-label','Undo');
 await expect(page.locator('#file-title')).toHaveText('保存');
 await expect(page.locator('#selection-name')).toHaveText('保存');
 await expect(page.locator('#link-url')).toHaveValue('https://example.org/未提交');
 expect(await page.evaluate(()=>document.querySelector('#canvas')===(window as any).__localeFrame)).toBe(true);
 expect(await page.evaluate(()=>(window as any).NotaleWorkbench.getSelection())).toEqual(['link']);
 await expect(page.frameLocator('#canvas').locator('[data-notale-id="link"]')).toHaveText('中文原文');
 const canvas=await page.locator('#canvas').contentFrame().locator('body').elementHandle();
 await expect.poll(()=>canvas!.evaluate(()=> (window as any).__NOTALE__.locale)).toBe('en-US');
 await page.locator('#file-menu-trigger').click();await page.locator('#open-find-replace').click();
 await page.locator('#find-query').fill('保存');
 const speaker=await context.newPage();await speaker.goto(`/present?document=${id}&speaker=1`,{waitUntil:'domcontentloaded'});
 await expect(speaker.locator('html')).toHaveAttribute('lang','en-US');
 await speaker.locator('.language-menu>summary').click();await speaker.getByRole('button',{name:'中文',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('lang','zh-CN');
 await expect(page.locator('#find-query')).toBeVisible();await expect(page.locator('#find-query')).toHaveValue('保存');
 await expect(page.locator('#undo')).toHaveAttribute('aria-label','撤销');
 await speaker.locator('.language-menu>summary').click();await speaker.getByRole('button',{name:'English',exact:true}).click();
 await expect(page.locator('#undo')).toHaveAttribute('aria-label','Undo');
 await expect(speaker.locator('.ps-end-button')).toHaveText('End Show');
 await expect(speaker.locator('#notes')).toContainText('讲稿：保存');
 const exported=await page.request.get(`/api/documents/${id}/export?locale=en-US`);expect(exported.ok()).toBe(true);
 const files=unzipSync(await exported.body());expect(strFromU8(files['index.html'])).toContain('<html lang="en-US">');
 expect(JSON.parse(strFromU8(files['notale-project.json'])).document).toEqual(original.document);
 expect((await page.request.get(`/api/documents/${id}/export?locale=invalid`)).status()).toBe(400);
 expect((await page.request.get('/api/documents/'+id).then(r=>r.json())).version).toBe(original.version);
 await page.reload({waitUntil:'domcontentloaded'});await expect(page.locator('#undo')).toHaveAttribute('aria-label','Undo');
 await page.screenshot({path:'.local/i18n-english.png'});
});
