"""Rebuild labelled overviews and compact contact sheets from the 40 authored slides.

Run: python3 resources/skills/style-director/build-previews.py
The source PNGs in shots/ are retained byte-for-byte.
"""

from pathlib import Path
import re

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent


def rows():
    matches = re.findall(r"^\| (\d{2}-[a-z0-9-]+) \|", (ROOT / "INDEX.md").read_text(), re.M)
    if len(matches) != 40 or len(set(matches)) != 40:
        raise ValueError("INDEX.md must list 40 unique style IDs")
    for key in matches:
        source = ROOT / "shots" / f"{key}.png"
        with Image.open(source) as image:
            if image.size != (1440, 810):
                raise ValueError(f"unexpected slide dimensions: {source}: {image.size}")
    return matches


def tile(image, width=700, height=394):
    thumbnail = image.convert("RGB")
    thumbnail.thumbnail((width, height), Image.Resampling.LANCZOS)
    return thumbnail


def overviews(ids, font):
    destination = ROOT / "overviews"
    destination.mkdir(exist_ok=True)
    for group in range(8):
        batch = ids[group * 5 : (group + 1) * 5]
        sheet = Image.new("RGB", (720, 5 * 440 + 16), "white")
        draw = ImageDraw.Draw(sheet)
        for position, key in enumerate(batch):
            y = 10 + position * 440
            draw.text((10, y), key, fill="#18211d", font=font)
            with Image.open(ROOT / "shots" / f"{key}.png") as image:
                sheet.paste(tile(image), (10, y + 32))
        sheet.save(destination / f"{group + 1:02d}.png")


def contacts(ids, font):
    destination = ROOT / "contact-sheets"
    destination.mkdir(exist_ok=True)
    index = [
        "# Compact style references",
        "",
        "40 original lecture-page references; 10 sheets with four images each.",
        "",
        "Generated by `python3 resources/skills/style-director/build-previews.py`.",
        "",
    ]
    for group in range(10):
        batch = ids[group * 4 : (group + 1) * 4]
        sheet = Image.new("RGB", (1488, 934), "white")
        draw = ImageDraw.Draw(sheet)
        for position, key in enumerate(batch):
            x = 16 + (position % 2) * 736
            y = 16 + (position // 2) * 459
            draw.text((x, y), key, fill="#18211d", font=font)
            with Image.open(ROOT / "shots" / f"{key}.png") as image:
                thumb = tile(image, 720, 405)
                sheet.paste(thumb, (x, y + 30))
        name = f"{group + 1:02d}.png"
        sheet.save(destination / name)
        index.extend(
            [
                f"## {name[:-4]} · {', '.join(batch)}",
                "",
                f"[Open sheet]({name}) · "
                + " · ".join(f"[{key}](../shots/{key}.png)" for key in batch),
                "",
                f"![Style references {name[:-4]}]({name})",
                "",
            ]
        )
    (destination / "README.md").write_text("\n".join(index), encoding="utf-8")


def main():
    ids = rows()
    font = ImageFont.truetype("DejaVuSans.ttf", 18)
    overviews(ids, font)
    contacts(ids, font)
    print("40 slides → 8 overviews and 10 contact sheets")


if __name__ == "__main__":
    main()
